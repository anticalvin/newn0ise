#!/usr/bin/env python3
"""Extracts the camera app's per-filter GLSL into a JS block (CAMFX) and splices it into index.html
between /*CAMFX:BEGIN*/ and /*CAMFX:END*/. Usage: gen_camfx.py <camera index.html> <newn0ise index.html>"""
import re,sys,json
cam=open(sys.argv[1],encoding='utf8').read().split('\n'); L=lambda a,b:'\n'.join(cam[a-1:b])
lib=L(307,312)+'\n'+L(339,362)           # hashes, luma, hueRot, hpal, mir, edge, heat, firePal, grade, vig
body=L(365,742)
disp=dict((int(n),fn) for n,fn in re.findall(r'f==(\d+)\) col=(fx_\w+)\(uv\)',L(743,810)))
meta=re.findall(r"F\('(\w+)','([^']+)','(\w+)',(\d+),'(#\w+)'(?:,(\d+),(\d+))?\)",L(905,925))
chunks={}
for m in re.finditer(r'^(?:vec3|float|vec2) (\w+)\([^)]*\)\s*\{.*?(?=^(?:vec3|float|vec2) \w+\(|^/\* ----|\Z)',body,re.S|re.M): chunks[m.group(1)]=m.group(0).strip()
helpers={k:v for k,v in chunks.items() if not k.startswith('fx_')}
out=[]
for id,label,cat,n,c,i,m in meta:
    n=int(n)
    if cat=='face': continue
    fn=disp[n]; out.append({'id':id,'label':label,'cat':cat,'c':c,'i':int(i or 55),'m':int(m or 45),'fn':fn,'hist':cat=='time','src':chunks[fn],'dep':[v for k,v in helpers.items() if k+'(' in chunks[fn]]})
js='/*CAMFX:BEGIN (generated by tools/gen_camfx.py from the n0ise camera app)*/\nconst CAMLIB='+json.dumps(lib)+';\nconst CAMFX='+json.dumps(out,separators=(',',':'))+';\n/*CAMFX:END*/'
t=open(sys.argv[2],encoding='utf8').read()
if '/*CAMFX:BEGIN' in t: t=re.sub(r'/\*CAMFX:BEGIN.*?/\*CAMFX:END\*/',lambda _:js,t,flags=re.S)
else: t=t.replace('const STACK={layers:[mkLayer(',js+'\n/*FUSE:HERE*/\nconst STACK={layers:[mkLayer(',1)
open(sys.argv[2],'w',encoding='utf8').write(t); print(len(out),'filters',len(js),'bytes')
